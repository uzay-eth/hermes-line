#!/usr/bin/env node
// The Hermes Line pane inside a REAL Hermes Desktop, on this Mac, without touching any existing
// profile or the owner's Desktop.
//
//   node tools/pane-preview/desktop-run.mjs [scene ...]      default: on_hold human_detected owner_connected ended
//
// How (the isolation recipe of Hermes Desktop's own e2e suite, apps/desktop/e2e/fixtures.ts):
//  - a throwaway sandbox under ~/.hermes/cache/scratch/hermes-line-l3/desktop/ with its own HERMES_HOME,
//    Electron userData and HOME; HERMES_DESKTOP_IGNORE_EXISTING + HERMES_DESKTOP_ISOLATED_BACKEND keep it
//    off the installed runtime, and a unique HERMES_DESKTOP_APP_NAME keeps it off the owner's
//    single-instance lock. ~/.hermes, its profiles (default, hermes-line-calls) and the owner's
//    Desktop state are never read or written.
//  - the dev Electron from the read-only Hermes checkout runs its built dist/ against the checkout
//    backend (`hermes serve` for the sandbox home).
//  - a copy of plugin/ is installed into <sandbox home>/plugins/hermes-line and enabled in that home's
//    config.yaml, so Desktop loads desktop/plugin.js (its unified-package door) and the gateway mounts
//    dashboard/plugin_api.py (the real REST API). The plugin's own `enabled` stays unset: no call
//    service, no adapter, no telephony.
//  - the call store is seeded per scene from the sample fixtures through L1's Store API
//    (seed_store.py), shifted so the scene's `now` is the launch time; TZ is set so wall-clock times
//    read as in the sample day. The model provider is the e2e suite's inert mock config; no chat
//    is sent. Chromium gets a dead proxy and Python dead HTTP(S)_PROXY values: nothing leaves the
//    machine.

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

import { measureCard } from './preview.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, '../..')
const HERMES = resolve(process.env.HERMES_AGENT_DIR || join(homedir(), '.hermes/hermes-agent'))
const DESKTOP = join(HERMES, 'apps/desktop')
export const PYTHON = join(HERMES, 'venv/bin/python')
const ELECTRON = join(HERMES, 'node_modules/electron/dist/Electron.app/Contents/MacOS/Electron')
export const SANDBOX = resolve(process.env.PANE_DESKTOP_SANDBOX || join(homedir(), '.hermes/cache/scratch/hermes-line-l3/desktop'))
const OUT = join(HERE, 'screenshots/desktop')
export const W = 1440
export const H = 900

const requireHermes = createRequire(join(HERMES, 'package.json'))
export const MAGICK = '/opt/homebrew/bin/magick'

const INERT_KEY = 'e2e-mock-key'
// _config_version matches the checkout's DEFAULT_CONFIG (hermes_cli/config_defaults.py) so the
// sandbox backend does not treat the home as an old install and fence itself for a migration.
const CONFIG = `# Hermes Line pane preview sandbox (generated by tools/pane-preview/desktop-run.mjs).
_config_version: ${configVersion()}
model:
  default: mock-model
  provider: custom
  base_url: http://127.0.0.1:9/v1
  context_length: 64000
custom_providers:
  - name: Mock
    base_url: http://127.0.0.1:9/v1
    key_env: OPENAI_API_KEY
auxiliary:
  title_generation:
    enabled: false
approvals:
  mode: 'off'
onboarding:
  run: false
plugins:
  enabled:
    - hermes-line
`

function configVersion() {
  const src = readFileSync(join(HERMES, 'hermes_cli/config_defaults.py'), 'utf8')
  const m = src.match(/"_config_version":\s*(\d+)/)
  if (!m) throw new Error('could not read _config_version from the Hermes checkout')
  return Number(m[1])
}

/** Processes whose HERMES_HOME is this sandbox (the gateway Desktop spawns outlives its window). */
function sandboxProcesses() {
  let out = ''
  try {
    out = execFileSync('lsof', ['+D', SANDBOX], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
  } catch (e) {
    out = e.stdout || '' // lsof exits 1 when nothing matches
  }
  const pids = [...new Set(out.split('\n').slice(1).map((l) => l.trim().split(/\s+/)[1]).filter(Boolean))]
  return pids.filter((pid) => {
    try {
      const env = execFileSync('ps', ['-E', '-ww', '-o', 'command=', '-p', pid], { encoding: 'utf8' })
      return env.includes(`HERMES_HOME=${SANDBOX}/`) || env.includes(`HOME=${SANDBOX} `)
    } catch {
      return false
    }
  })
}

/** Stop only processes that run inside this sandbox; never anything else. */
export async function stopSandboxProcesses() {
  for (let round = 0; round < 10; round++) {
    const pids = sandboxProcesses()
    if (!pids.length) return
    for (const pid of pids) {
      try {
        process.kill(Number(pid), 'SIGTERM')
      } catch {}
    }
    await new Promise((r) => setTimeout(r, 1000))
  }
  const left = sandboxProcesses()
  if (left.length) throw new Error(`sandbox processes did not stop: ${left.join(', ')}`)
}

function assertSandboxIdle() {
  if (!existsSync(SANDBOX)) return
  const live = sandboxProcesses()
  if (live.length) throw new Error(`processes still use the sandbox (pids ${live.join(', ')}); stop them first`)
}

// Same filter as the e2e suite: no credentials and no inherited HERMES_* runtime settings.
function cleanEnv() {
  const out = {}
  for (const [k, v] of Object.entries(process.env)) {
    if (!v) continue
    if (/(_API_KEY|_TOKEN|_SECRET|_PASSWORD|_CREDENTIALS|_ACCESS_KEY|_PRIVATE_KEY|_OAUTH_TOKEN)$/.test(k)) continue
    if (/_BASE_URL$/.test(k) || /^AWS_/.test(k)) continue
    if (k.startsWith('HERMES_') && !k.startsWith('HERMES_DESKTOP_')) continue
    out[k] = v
  }
  return out
}

/** POSIX TZ whose local time of `realNow` equals the sample-day local time of `sceneNow` (minutes). */
function tzFor(sceneNowIso, realNowMs, sampleUtcOffsetMin = -480) {
  const deltaMin = Math.round((Date.parse(sceneNowIso) - realNowMs) / 60000)
  let off = (((deltaMin + sampleUtcOffsetMin) % 1440) + 1440) % 1440
  if (off > 720) off -= 1440
  const sign = off <= 0 ? '+' : '-' // POSIX TZ signs are inverted
  const a = Math.abs(off)
  return `SAMPLE${sign}${String(Math.floor(a / 60)).padStart(2, '0')}:${String(a % 60).padStart(2, '0')}`
}

export function prepareSandbox() {
  if (!SANDBOX.includes('/cache/scratch/')) throw new Error('sandbox must live under ~/.hermes/cache/scratch')
  assertSandboxIdle()
  rmSync(SANDBOX, { recursive: true, force: true })
  const home = join(SANDBOX, 'hermes-home')
  const userData = join(SANDBOX, 'electron-user-data')
  mkdirSync(join(home, 'plugins'), { recursive: true })
  mkdirSync(userData, { recursive: true })
  cpSync(join(REPO, 'plugin'), join(home, 'plugins/hermes-line'), {
    recursive: true,
    filter: (src) => !src.includes('__pycache__')
  })
  writeFileSync(join(home, 'config.yaml'), CONFIG)
  writeFileSync(join(home, '.env'), `MOCK_API_KEY=${INERT_KEY}\nOPENAI_API_KEY=${INERT_KEY}\n`)
  writeFileSync(join(userData, 'window-state.json'), JSON.stringify({ x: 0, y: 0, width: W, height: H, isMaximized: false }))
  writeFileSync(join(userData, 'zoom-state.json'), JSON.stringify({ zoomLevel: 0 }))
  return { home, userData }
}

async function shootScene(sceneId, { home, userData }, index) {
  const scene = index.scenes.find((s) => s.id === sceneId)
  const launchAt = Date.now() + 20000 // the backend is serving ~20 s after launch
  const offset = (launchAt - Date.parse(scene.now)) / 1000
  execFileSync(PYTHON, ['-I', join(HERE, 'seed_store.py'), '--db', join(home, 'plugin-data/hermes-line/line.db'), '--scene', sceneId, '--offset', String(offset)], { stdio: 'inherit' })
  const { app, page, logs, flushLog } = await launchDesktopWithPane({ home, userData, label: sceneId, tz: tzFor(scene.now, launchAt) })
  try {
    // Boot takes a variable minute or two; re-seed now so the scene's `now` is the moment of the
    // final fetch (the REST layer opens the store per request), then reload the pane's view.
    const reseedAt = Date.now() + 1500
    execFileSync(PYTHON, ['-I', join(HERE, 'seed_store.py'), '--db', join(home, 'plugin-data/hermes-line/line.db'), '--scene', sceneId, '--offset', String((reseedAt - Date.parse(scene.now)) / 1000)], { stdio: 'ignore' })
    const wait = reseedAt - Date.now()
    if (wait > 0) await page.waitForTimeout(wait)
    await page.reload()
    await page.locator('.hlc-field').first().waitFor({ state: 'visible', timeout: 120000 })
    await page.evaluate(() => document.fonts.ready)
    await page.waitForTimeout(800)
    mkdirSync(OUT, { recursive: true })
    const file = join(OUT, `${sceneId}.png`)
    await capture(app, page, file, logs)
    const box = await page.evaluate(() => {
      const root = document.querySelector('.hlp-root')
      let el = root
      // The pane's own tile: the nearest ancestor that is wider than the pane body's content column.
      while (el && el.parentElement && el.parentElement.getBoundingClientRect().width - root.getBoundingClientRect().width < 4) el = el.parentElement
      const r = root.getBoundingClientRect()
      return { x: r.left, y: 0, width: r.width, height: window.innerHeight, paneTop: r.top, dpr: window.devicePixelRatio, inner: [window.innerWidth, window.innerHeight] }
    })
    const contrast = await page.evaluate(measureCard)
    const theme = await page.evaluate(() => {
      const cs = getComputedStyle(document.documentElement)
      const names = ['--ui-accent', '--theme-primary', '--theme-midground', '--dt-primary-solid', '--ui-red', '--dt-destructive', '--ui-base']
      return { skin: document.documentElement.dataset.hermesTheme || null, mode: document.documentElement.dataset.hermesMode || null, vars: Object.fromEntries(names.map((n) => [n, cs.getPropertyValue(n).trim()])) }
    })
    writeFileSync(join(OUT, `${sceneId}.json`), `${JSON.stringify({ scene: sceneId, pane: box, theme, contrast }, null, 2)}\n`)
    // Pane crop with the same 28 px app strip as round 4, and a round 4 | Desktop sheet.
    const crop = join(OUT, `${sceneId}-pane.png`)
    const dpr = box.dpr
    const x = Math.round((box.x - 28) * dpr)
    execFileSync(MAGICK, [file, '-crop', `${Math.round((box.width + 28) * dpr)}x${H * dpr}+${x}+0`, '+repage', crop])
    const r4 = join(HERE, 'screenshots/round4', `${sceneId}.png`)
    if (existsSync(r4)) {
      execFileSync(MAGICK, ['montage', '-label', 'Round 4 (offline harness)', r4, '-label', 'Hermes Desktop (real app, real REST API)', crop,
        '-font', '/System/Library/Fonts/Helvetica.ttc', '-tile', '2x1', '-geometry', '+24+16', '-pointsize', '26', '-background', '#e9e9ec', join(OUT, `compare-${sceneId}.png`)])
    }
    const worst = contrast.rows.filter((r) => r.ratio < r.need)
    console.log(`  card ${contrast.card} (${contrast.tone}) skin=${theme.skin} accent=${theme.vars['--ui-accent']} contrast ${worst.length ? 'FAIL ' + JSON.stringify(worst) : 'ok'}`)
    console.log(`${file}  pane x=${box.x} w=${box.width} top=${box.paneTop} window=${box.inner.join('x')} dpr=${box.dpr}`)
  } finally {
    flushLog()
    await app.close().catch(() => {})
    await stopSandboxProcesses()
  }
}

/**
 * Launch the sandboxed real Hermes Desktop and bring up the Hermes Line pane (opt-in enable as a user
 * would, right sidebar open, window 1440 x 900). Resolves once the pane is mounted; it may still
 * show its empty state when no call exists yet. Caller closes `app` and stops sandbox processes.
 */
export async function launchDesktopWithPane({ home, userData, label, tz }) {
  const { _electron } = requireHermes('playwright')
  const env = {
    ...cleanEnv(),
    HOME: SANDBOX,
    HERMES_HOME: home,
    HERMES_DESKTOP_USER_DATA_DIR: userData,
    HERMES_DESKTOP_IGNORE_EXISTING: '1',
    HERMES_DESKTOP_ISOLATED_BACKEND: '1',
    HERMES_DESKTOP_HERMES_ROOT: HERMES,
    HERMES_DESKTOP_APP_NAME: `HermesLinePanePreview-${Date.now()}`,
    HERMES_DESKTOP_SKIP_QUIT_CONFIRM: '1',
    HERMES_DESKTOP_SKIP_PROTOCOL_REGISTRATION: '1',
    OPENAI_API_KEY: INERT_KEY,
    HTTP_PROXY: 'http://127.0.0.1:9',
    HTTPS_PROXY: 'http://127.0.0.1:9',
    ALL_PROXY: 'http://127.0.0.1:9',
    NO_PROXY: '127.0.0.1,localhost',
    ...(tz ? { TZ: tz } : {})
  }
  const app = await _electron.launch({
    executablePath: ELECTRON,
    // sRGB rendering so captures compare 1:1 with the harness (macOS otherwise captures in the
    // display's colour space, which reads as a colour cast next to sRGB images).
    args: [DESKTOP, '--no-sandbox', '--force-color-profile=srgb', '--proxy-server=127.0.0.1:9', '--proxy-bypass-list=127.0.0.1;localhost'],
    env,
    cwd: DESKTOP,
    timeout: 120000
  })
  const logPath = join(SANDBOX, `electron-${label}.log`)
  const logs = []
  app.process().stdout?.on('data', (d) => logs.push(String(d)))
  app.process().stderr?.on('data', (d) => logs.push(String(d)))
  const flushLog = () => writeFileSync(logPath, logs.join(''))
  try {
    // Boot and splash windows come and go; the main window is the one that ends up showing the pane.
    let page = null
    const deadline = Date.now() + 240000
    const opened = new WeakSet()
    const lastTry = new WeakMap()
    const consoleHooked = new WeakSet()
    const enabledTried = new WeakSet()
    const fallbackDone = new WeakSet()
    const launchedAt = Date.now()
    while (!page && Date.now() < deadline) {
      for (const w of app.windows()) {
        if (w.isClosed()) continue
        if (await w.locator('.hlp-root').count().catch(() => 0)) {
          page = w
          break
        }
        // A fresh layout keeps the right sidebar collapsed; the pane is registered there
        // (placement 'right'). Open it once the app is up, the way a user would.
        const due = Date.now() - launchedAt > 75000 && (!opened.has(w) || Date.now() - (lastTry.get(w) || 0) > 30000)
        if (due) {
          opened.add(w)
          lastTry.set(w, Date.now())
          logs.push(`[pane-preview] window ${w.url()}\n`)
          const labels = await w.locator('button[aria-label]').evaluateAll((els) => els.map((e) => e.getAttribute('aria-label')))
          logs.push(`[pane-preview] titlebar/button labels: ${JSON.stringify(labels)}\n`)
          const noThanks = w.getByRole('button', { name: 'No thanks' })
          if (await noThanks.count()) await noThanks.first().click().catch(() => {})
          if (!consoleHooked.has(w)) {
            consoleHooked.add(w)
            w.on('console', (m) => logs.push(`[renderer ${m.type()}] ${m.text()}\n`))
          }
          // A unified package's desktop half is opt-in (Capabilities > Plugins), like its Python half.
          // Turn it on in THIS sandbox the way a user would; fall back to the same persisted decision.
          if (!enabledTried.has(w)) {
            enabledTried.add(w)
            let how = 'none'
            try {
              await w.getByText('Capabilities', { exact: true }).first().click({ timeout: 5000 })
              await w.waitForTimeout(1500)
              await w.getByText('Plugins', { exact: true }).first().click({ timeout: 5000 })
              await w.waitForTimeout(2000)
              await w.getByPlaceholder('Search plugins').fill('Hermes Line').catch(() => {})
              await w.waitForTimeout(1500)
              await w.screenshot({ path: join(SANDBOX, `debug-${label}-capabilities.png`) }).catch(() => {})
              const sws = await w.getByRole('switch').evaluateAll((els) =>
                els.map((e) => ({ label: e.getAttribute('aria-label') || (e.closest('[class]')?.textContent || '').slice(0, 80), checked: e.getAttribute('aria-checked') }))
              )
              logs.push(`[pane-preview] switches after search: ${JSON.stringify(sws)}\n`)
              let sw = w.getByRole('switch', { name: /hermes line|hermes-line/i })
              if (!(await sw.count())) {
                // The row's switch: the smallest element holding the name and one switch.
                const row = w.locator('div').filter({ hasText: 'Hermes Line' }).filter({ has: w.getByRole('switch') }).last()
                sw = row.getByRole('switch')
              }
              const n = await sw.count()
              logs.push(`[pane-preview] Hermes Line switches found: ${n}\n`)
              if (n === 1) {
                // The paired row can already read "on" (agent half enabled in config.yaml) while the
                // desktop half is still opt-in off: a user then switches it off and on again.
                const was = await sw.getAttribute('aria-checked')
                if (was === 'true') {
                  await sw.click()
                  await w.waitForTimeout(1500)
                }
                await sw.click()
                await w.waitForTimeout(1500)
                if ((await sw.getAttribute('aria-checked')) === 'true') how = was === 'true' ? 'ui-switch-off-on' : 'ui-switch'
              }
            } catch (e) {
              logs.push(`[pane-preview] capabilities path failed: ${e}\n`)
            }
            if (how === 'none') {
              await w.evaluate(() => {
                const KEY = 'hermes.desktop.pluginDecisions.v2'
                const prev = JSON.parse(window.localStorage.getItem(KEY) || '{}')
                window.localStorage.setItem(KEY, JSON.stringify({ ...prev, 'hermes-line': true }))
              })
              await w.reload()
              how = 'stored-decision+reload'
            }
            logs.push(`[pane-preview] enabled hermes-line via ${how}\n`)
            await w.waitForTimeout(3000)
            await w.getByText('New session', { exact: true }).first().click({ timeout: 5000 }).catch(() => {})
            await w.waitForTimeout(1500)
          }
          const show = w.getByRole('button', { name: 'Show right sidebar', exact: true })
          if (await show.count()) await show.first().click().catch((e) => logs.push(`[pane-preview] click failed: ${e}\n`))
          await w.waitForTimeout(2500)
          if (!(await w.locator('.hlp-root').count()) && !fallbackDone.has(w)) {
            fallbackDone.add(w)
            await w.evaluate(() => {
              const KEY = 'hermes.desktop.pluginDecisions.v2'
              const prev = JSON.parse(window.localStorage.getItem(KEY) || '{}')
              window.localStorage.setItem(KEY, JSON.stringify({ ...prev, 'hermes-line': true }))
            })
            await w.reload()
            logs.push('[pane-preview] UI path did not load the desktop half; applied the stored decision + reload\n')
            await w.waitForTimeout(4000)
            const show2 = w.getByRole('button', { name: 'Show right sidebar', exact: true })
            if (await show2.count()) await show2.first().click().catch(() => {})
            await w.waitForTimeout(2500)
          }
          const tabs = await w.locator('[role="tab"]').evaluateAll((els) => els.map((e) => (e.textContent || '').trim()))
          logs.push(`[pane-preview] tabs: ${JSON.stringify(tabs)}\n`)
          const calls = w.getByRole('tab', { name: 'Calls' })
          if (await calls.count()) await calls.first().click().catch(() => {})
          await w.screenshot({ path: join(SANDBOX, `debug-${label}-sidebar.png`) }).catch(() => {})
        }
      }
      if (!page) await new Promise((r) => setTimeout(r, 1000))
    }
    if (!page) {
      mkdirSync(OUT, { recursive: true })
      for (const [i, w] of app.windows().entries()) await w.screenshot({ path: join(SANDBOX, `debug-${label}-${i}.png`) }).catch(() => {})
      flushLog()
      throw new Error(`pane never appeared for ${label}; see ${logPath} and ${SANDBOX}/debug-*.png`)
    }
    await app.evaluate(({ BrowserWindow }, size) => {
      for (const w of BrowserWindow.getAllWindows()) {
        w.setContentSize(size.W, size.H)
        w.setPosition(0, 0)
      }
    }, { W, H })
    flushLog()
    return { app, page, logs, flushLog }
  } catch (error) {
    flushLog()
    await app.close().catch(() => {})
    await stopSandboxProcesses()
    throw error
  }
}

/**
 * Screenshot the window; refuses a blank capture. `raise: 'always'` brings the window forward before
 * every shot (one-off captures); `'on-blank'` only when a shot comes back blank, so periodic live
 * captures do not keep stealing focus on the machine running the trial.
 */
export async function capture(app, page, file, logs = [], { raise = 'always' } = {}) {
    // An occluded macOS window can stop painting: bring it forward, keep it unthrottled, force a
    // repaint, and refuse a blank capture.
    let ok = false
    for (let attempt = 0; attempt < 5 && !ok; attempt++) {
      if (raise === 'always' || attempt > 0) await app.evaluate(({ BrowserWindow }) => {
        for (const w of BrowserWindow.getAllWindows()) {
          w.webContents.setBackgroundThrottling(false)
          w.show()
          w.focus()
          w.moveTop()
          w.webContents.invalidate()
        }
      })
      if (raise === 'always' || attempt > 0) await page.waitForTimeout(1500)
      await page.screenshot({ path: file, animations: 'disabled' })
      const sd = Number(execFileSync(MAGICK, [file, '-colorspace', 'Gray', '-format', '%[fx:standard_deviation]', 'info:'], { encoding: 'utf8' }))
      ok = sd > 0.02
      if (!ok) logs.push(`[pane-preview] blank capture (sd ${sd}); retrying\n`)
    }
    if (!ok) throw new Error(`${file}: window never painted`)
}

export function assertDesktopTools() {
  for (const p of [ELECTRON, PYTHON, join(DESKTOP, 'dist/electron-main.mjs')]) if (!existsSync(p)) throw new Error(`missing ${p}`)
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const index = JSON.parse(readFileSync(join(HERE, 'fixtures/index.json'), 'utf8'))
  const scenes = process.argv.slice(2).length ? process.argv.slice(2) : ['on_hold', 'human_detected', 'owner_connected', 'ended']
  assertDesktopTools()
  const dirs = prepareSandbox()
  for (const s of scenes) await shootScene(s, dirs, index)
}
